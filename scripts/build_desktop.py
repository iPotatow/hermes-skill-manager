#!/usr/bin/env python3
"""Emit a single ESM entry: Hermes disk loader rejects relative imports."""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IMPORT_RE = re.compile(r"import\s*\{([^}]+)\}\s*from\s*'([^']+)'\s*\n")
ALLOWED = {'@hermes/plugin-sdk', 'react', 'react/jsx-runtime'}


def build() -> str:
    imports: dict[str, set[str]] = {}
    bodies = []
    for name in ('plugin-core.js', 'plugin.js'):
        source = (ROOT / 'src' / name).read_text(encoding='utf-8')
        def collect(match: re.Match) -> str:
            names, module = match.groups()
            if module not in ALLOWED:
                raise ValueError(f'Unsupported import: {module}')
            imports.setdefault(module, set()).update(n.strip() for n in names.split(',') if n.strip())
            return ''
        body = IMPORT_RE.sub(collect, source)
        if name == 'plugin.js':
            body = body.replace("import core from './plugin-core.js'\n", '')
        if re.search(r'\bimport\s', body):
            raise ValueError(f'Unprocessed import in {name}')
        if name == 'plugin-core.js':
            body = 'const core = (() => {\n' + body.replace('export default {', 'return {', 1) + '\n})()\n'
        bodies.append(body)
    header = '// Generated by scripts/build_desktop.py; edit src/ instead.\n'
    header += ''.join(f"import {{ {', '.join(sorted(names))} }} from '{module}'\n" for module, names in sorted(imports.items()))
    return header + '\n' + '\n'.join(bodies)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'desktop' / 'plugin.js'
    rendered = build()
    if args.check:
        if not output.is_file() or output.read_text(encoding='utf-8') != rendered:
            raise SystemExit('desktop/plugin.js is stale; run python3 scripts/build_desktop.py')
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rendered, encoding='utf-8')


if __name__ == '__main__':
    main()
